#!/usr/bin/env python3
"""Keeps the template seed in migrations/20261207_creative_studio_v2.sql identical to creative_studio/presets/library.json (M8c).

    python3 scripts/creative_presets_seed.py --check    # exit 1 when the migration's seed block differs from the library (CI / tests)
    python3 scripts/creative_presets_seed.py --write    # rewrite the block between the BEGIN / END TEMPLATE SEED markers

The library is validated first (hq_creative_presets.validate): a library that could weaken a gate never reaches SQL.
NOTE: 20261207_creative_studio_v2.sql is frozen once it is on overnight-build (MIGRATIONS.md rule 2); after that a library change needs a new migration file.
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import hq_creative_presets as presets  # noqa: E402

MIGRATION = os.path.join(ROOT, "migrations", "20261207_creative_studio_v2.sql")
BEGIN = "-- BEGIN TEMPLATE SEED (generated by scripts/creative_presets_seed.py from creative_studio/presets/library.json; do not edit by hand)\n"
END = "-- END TEMPLATE SEED\n"


def _q(s: str) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def block(lib: dict) -> str:
    rows = []
    for r in presets.seed_rows(lib):
        spec = json.dumps(r["spec"], sort_keys=True, ensure_ascii=False)
        if "$j$" in spec:
            raise SystemExit("spec contains the dollar-quote tag")
        hooks = "array[" + ", ".join(_q(h) for h in r["hooks"]) + "]::text[]"
        rows.append(f"  ({_q(r['slug'])}, {_q(r['office'])}, {_q(r['module'])}, {_q(r['kind'])}, {_q(r['title'])}, {hooks}, $j${spec}$j$::jsonb, {_q(r['source'])})")
    return (BEGIN + "insert into fz_creative.templates (slug, scope, module, kind, title, hooks, spec, source) values\n" + ",\n".join(rows) + "\n"
            "on conflict (slug) do update set scope = excluded.scope, module = excluded.module, kind = excluded.kind, title = excluded.title, hooks = excluded.hooks, spec = excluded.spec,\n"
            "  source = excluded.source, updated_at = now()\n"
            "  where fz_creative.templates.updated_by = 'migration';                        -- the owner's edits stay\n" + END)


def current(text: str) -> str:
    a, b = text.index(BEGIN), text.index(END)
    return text[a:b + len(END)]


def main(argv: list[str]) -> int:
    lib = presets.load_library()
    with open(MIGRATION) as f:
        text = f.read()
    want = block(lib)
    if "--write" in argv:
        with open(MIGRATION, "w") as f:
            f.write(text.replace(current(text), want))
        print(f"wrote {len(lib['templates'])} templates")
        return 0
    if current(text) != want:
        print("STALE: the migration's template seed differs from creative_studio/presets/library.json (run scripts/creative_presets_seed.py --write)")
        return 1
    print(f"ok: {len(lib['templates'])} templates")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
