#!/usr/bin/env python3
"""The reviewed allowlist of privileged grants (M4 security watch): ops/expected_grants.tsv and the generated block of fz_expected_grants() in
migrations/20261130_security_hardening_v1.sql.

Source: the replica after a full apply, whose ACLs equal the reviewed ops/ACL_MANIFEST_public.tsv (scripts/acl_manifest.py --check). Taken: every privileged item of
category 'grant' (fz_privileged_items()). NEVER taken, whatever the replica holds:
  * standing findings (any anon / authenticated write; service_role UPDATE / DELETE / TRUNCATE on audit_log or ledger): always reported;
  * anon / authenticated read of a table with RLS off (':rls-off');
  * anything in the fz_archive* schemas (the archive is never granted).

  REPLICA_URL=... scripts/expected_grants.py --write   regenerate both files (a reviewed change)
  REPLICA_URL=... scripts/expected_grants.py --check   fail if the database, the TSV and the migration block disagree
  scripts/expected_grants.py --check                    (no database) fail if the TSV and the migration block disagree
"""
import argparse, os, re, subprocess, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TSV = os.path.join(ROOT, "ops", "expected_grants.tsv")
MIG = os.path.join(ROOT, "migrations", "20261130_security_hardening_v1.sql")
BEGIN, END = "    -- BEGIN EXPECTED GRANTS (generated: scripts/expected_grants.py --write)\n", "    -- END EXPECTED GRANTS\n"
QUERY = ("select item from public.fz_privileged_items() where category = 'grant' and item !~ ':rls-off$' and item !~ '^[a-z-]+:fz_archive' "
         "and item !~ '^definer:fz_archive' order by 1")


def from_db(url):
    out = subprocess.run(["psql", url, "-At", "-v", "ON_ERROR_STOP=1", "-c", QUERY], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f"expected_grants: cannot query the replica: {out.stderr.strip()[:300]}")
    return sorted(l for l in out.stdout.splitlines() if l)   # sorted here, not by the database: its collation differs between hosts (CI vs local)


def from_tsv():
    if not os.path.exists(TSV):
        return []
    return [l.split("\t")[0] for l in open(TSV).read().splitlines() if l and not l.startswith("#")]


def from_mig():
    s = open(MIG).read()
    block = s[s.index(BEGIN) + len(BEGIN):s.index(END)]
    return [re.match(r"\s*\('(.*)'\),\s*$", l).group(1).replace("''", "'") for l in block.splitlines() if l.strip()]


def write(items):
    with open(TSV, "w") as f:
        f.write("# Reviewed allowlist of privileged grants (generated by scripts/expected_grants.py from the replica; see its docstring). One item per line.\tcomment\n")
        for it in items:
            f.write(it + "\tfrom the reviewed ACL manifest\n")
    s = open(MIG).read()
    a, b = s.index(BEGIN) + len(BEGIN), s.index(END)
    open(MIG, "w").write(s[:a] + "".join(f"    ('{it.replace(chr(39), chr(39) * 2)}'),\n" for it in items) + s[b:])


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--url", default=os.environ.get("REPLICA_URL")); ap.add_argument("--write", action="store_true"); ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.write:
        if not a.url:
            sys.exit("expected_grants: --write needs REPLICA_URL")
        items = from_db(a.url); write(items); print(f"wrote {len(items)} expected grants"); return 0
    tsv, mig = from_tsv(), from_mig()
    bad = 0
    if tsv != sorted(tsv):
        print("expected_grants: ops/expected_grants.tsv is not sorted (regenerate with --write)"); bad = 1
    if tsv != mig:
        print("expected_grants: ops/expected_grants.tsv and the migration block differ:", sorted(set(tsv) ^ set(mig))[:20]); bad = 1
    if a.url:
        db = from_db(a.url)
        if db != tsv:
            print("expected_grants: the database differs from the reviewed list. Not on the list:", sorted(set(db) - set(tsv))[:20], "missing:", sorted(set(tsv) - set(db))[:20]); bad = 1
    if not bad:
        print(f"expected_grants: {len(tsv)} expected grants, list and migration agree" + (" with the database" if a.url else ""))
    return bad


if __name__ == "__main__":
    sys.exit(main())
