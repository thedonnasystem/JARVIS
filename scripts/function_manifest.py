#!/usr/bin/env python3
"""Generated function manifest: replaces hand-maintaining ops/EXPECTED_NEW_FUNCTIONS.txt.

Run AFTER scripts/replica/run.sh against the same scratch database (REPLICA_URL). It lists the public functions of that
database with md5(pg_get_functiondef) in the baseline's own format (`name(argtypes) md5`) and compares them with the live
baseline (ops/live_functions_baseline_*.txt) to produce an added / changed / removed report.

Honesty about what the replica can prove: the replica is NOT the live database. Its seed (scripts/replica/01-03, plus the
exact-live-text restore in ops/rollback_phase1.sql) only approximates most live functions, so a replica md5 differing from the live baseline md5 proves nothing for those. So:
  * added    = in replica, not in baseline (minus replica scaffolding: functions that already exist in the seed but not live,
               and extension-owned functions such as pgcrypto). Reliable.
  * removed  = in baseline, absent from the replica. Reliable.
  * changed  = md5 differs from baseline AND the seed's copy of that function was byte-identical to live (so the
               difference was caused by a migration). Reliable.
  * unverifiable = md5 differs from baseline but the seed copy already differed from live; the replica cannot say whether a
               migration changed it. Check against production with ops/verify_live.sql (read-only) before/after deploy.

Usage
  REPLICA_URL=postgresql://postgres:pw@localhost:5432/<scratch> scripts/function_manifest.py            # report
  ...                                                                                  --check   # also fail if it differs from ops/EXPECTED_NEW_FUNCTIONS.txt
  ...                                                                                  --write   # one-edit workflow: regenerate ops/EXPECTED_NEW_FUNCTIONS.txt
  ...                                                                                  --manifest-out FILE   # write the full public manifest
Exit: 0 ok, 1 --check mismatch, 2 cannot run (no REPLICA_URL / psql / seed database), so callers can tell SKIPPED from FAIL.
"""
import argparse
import glob
import os
import re
import subprocess
import sys
import urllib.parse

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
EXPECTED = os.path.join(ROOT, "ops", "EXPECTED_NEW_FUNCTIONS.txt")
SEED_FILES = ["01_tables.sql", "02_constraints.sql", "03_funcs.sql"]
MANIFEST_SQL = ("select p.oid::regprocedure::text || ' ' || md5(pg_get_functiondef(p.oid)) from pg_proc p "
                "where p.pronamespace = 'public'::regnamespace and p.prokind = 'f' "
                "and not exists (select 1 from pg_depend d where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e') "
                "order by 1")
HEADERS = {
    "ADD": "# Functions the pending migrations ADD (ops/verify_live.sql drift output should show exactly these as new, nothing else)",
    "CHANGE": "# Functions the pending migrations CHANGE (md5 must differ from the baseline)",
    "REMOVE": "# Functions the pending migrations REMOVE (must be absent from the live manifest after deploy)",
}
FOOTER = "# GENERATED by scripts/function_manifest.py --write from a replica run. Do not hand-edit; re-run it after changing migrations."


class CannotRun(Exception):
    pass


def psql(url, *args, sql=None):
    cmd = ["psql", "-X", "-q", "-At", "-v", "ON_ERROR_STOP=1", url, *args]
    r = subprocess.run(cmd, capture_output=True, text=True, input=sql)
    if r.returncode != 0:
        raise CannotRun(f"psql failed: {r.stderr.strip()[:300]}")
    return r.stdout


def parse_manifest(text):
    """{signature: md5} from `signature md5` lines (comments and blanks ignored)."""
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        sig, _, md5 = line.rpartition(" ")
        if not sig or not re.fullmatch(r"[0-9a-f]{32}", md5):
            raise ValueError(f"bad manifest line: {line!r}")
        out[sig] = md5
    return out


def latest_baseline():
    c = sorted(glob.glob(os.path.join(ROOT, "ops", "live_functions_baseline_*.txt")))
    if not c:
        raise CannotRun("no ops/live_functions_baseline_*.txt")
    return c[-1]


def seed_manifest(url, pre_files=()):
    """Manifest of a throwaway database seeded with scripts/replica/01-03 plus pre_files (created and dropped on the same
    server). pre_files are SQL known to restore exact live definitions, e.g. ops/rollback_phase1.sql."""
    u = urllib.parse.urlsplit(url)
    admin = urllib.parse.urlunsplit(u._replace(path="/postgres"))
    name = f"infra_seed_{os.getpid()}"
    seed_url = urllib.parse.urlunsplit(u._replace(path="/" + name))
    psql(admin, "-c", f'create database "{name}"')
    try:
        psql(seed_url, "-c", "do $$ declare r text; begin foreach r in array array['authenticated','service_role','anon'] loop "
             "if not exists (select 1 from pg_roles where rolname = r) then execute format('create role %I nologin', r); end if; end loop; end $$")
        for f in SEED_FILES:
            psql(seed_url, "-f", os.path.join(ROOT, "scripts", "replica", f))
        for f in pre_files:
            psql(seed_url, "-f", f)
        return parse_manifest(psql(seed_url, "-c", MANIFEST_SQL))
    finally:
        subprocess.run(["psql", "-X", "-q", admin, "-c", f'drop database if exists "{name}"'], capture_output=True, text=True)


def diff(baseline, final, seed):
    scaffolding = {s for s in seed if s not in baseline}
    added = sorted(s for s in final if s not in baseline and s not in scaffolding)
    removed = sorted(s for s in baseline if s not in final)
    changed, unverifiable = [], []
    for s in sorted(final):
        if s in baseline and final[s] != baseline[s]:
            (changed if seed.get(s) == baseline[s] else unverifiable).append(s)
    return {"added": added, "changed": changed, "removed": removed, "unverifiable": unverifiable, "scaffolding": sorted(scaffolding)}


def render_expected(d):
    lines = []
    for key, items in (("ADD", d["added"]), ("CHANGE", d["changed"]), ("REMOVE", d["removed"])):
        lines.append(HEADERS[key])
        lines += items
    lines.append(FOOTER)
    return "\n".join(lines) + "\n"


def parse_expected(text):
    """{'ADD': set, 'CHANGE': set, 'REMOVE': set} from the (hand-written or generated) EXPECTED_NEW_FUNCTIONS format."""
    sec, out = None, {"ADD": set(), "CHANGE": set(), "REMOVE": set()}
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("#"):
            m = re.match(r"#\s*Functions\b.*?\b(ADD|CHANGE|REMOVE)\b", line)
            sec = m.group(1) if m else sec if not line.startswith("# GENERATED") else None
            if line.startswith("# enforce_build_rules"):
                sec = None
            continue
        if sec:
            out[sec].add(line)
    return out


def compare_expected(d, expected):
    got = {"ADD": set(d["added"]), "CHANGE": set(d["changed"]), "REMOVE": set(d["removed"])}
    problems = []
    for k in ("ADD", "CHANGE", "REMOVE"):
        for s in sorted(got[k] - expected[k]):
            problems.append(f"{k}: {s} is produced by the migrations but missing from ops/EXPECTED_NEW_FUNCTIONS.txt")
        for s in sorted(expected[k] - got[k]):
            problems.append(f"{k}: {s} is listed in ops/EXPECTED_NEW_FUNCTIONS.txt but the migrations do not produce it")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generated function manifest and added/changed/removed report")
    ap.add_argument("--url", default=os.environ.get("REPLICA_URL"))
    ap.add_argument("--baseline")
    ap.add_argument("--expected", default=EXPECTED)
    ap.add_argument("--pre", action="append", help="SQL that restores exact live definitions into the seed (default: ops/rollback_phase1.sql if present)")
    ap.add_argument("--manifest-out")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    try:
        if not a.url:
            raise CannotRun("REPLICA_URL not set")
        base_path = a.baseline or latest_baseline()
        with open(base_path) as f:
            baseline = parse_manifest(f.read())
        final = parse_manifest(psql(a.url, "-c", MANIFEST_SQL))
        pre = a.pre if a.pre is not None else [p for p in [os.path.join(ROOT, "ops", "rollback_phase1.sql")] if os.path.exists(p)]
        seed = seed_manifest(a.url, pre)
    except CannotRun as e:
        print(f"function_manifest: cannot run: {e}")
        return 2
    if not final:
        print("function_manifest: the database has no public functions; run scripts/replica/run.sh first")
        return 2
    d = diff(baseline, final, seed)
    if a.manifest_out:
        with open(a.manifest_out, "w") as f:
            f.write("".join(f"{s} {final[s]}\n" for s in sorted(final)))
    print(f"function_manifest: baseline={os.path.basename(base_path)} ({len(baseline)} fns), replica={len(final)} fns")
    for k in ("added", "changed", "removed"):
        print(f"  {k} ({len(d[k])})" + "".join(f"\n    {s}" for s in d[k]))
    print(f"  unverifiable in replica ({len(d['unverifiable'])}): seed copy already differed from live; check with ops/verify_live.sql after deploy")
    print(f"  replica scaffolding ignored ({len(d['scaffolding'])})")
    if a.write:
        with open(a.expected, "w") as f:
            f.write(render_expected(d))
        print(f"wrote {os.path.relpath(a.expected, ROOT)}")
        return 0
    if a.check:
        with open(a.expected) as f:
            problems = compare_expected(d, parse_expected(f.read()))
        for p in problems:
            print("MISMATCH:", p)
        if problems:
            print("fix: scripts/function_manifest.py --write   (then review the diff and commit)")
            return 1
        print("matches ops/EXPECTED_NEW_FUNCTIONS.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main())
