def compare_baseline(p, s, t, base, base_ev, fresh, acl_path):
    """Production baseline snapshot (hashed file) vs the committed ACL manifest of a head (hashed blob): a comparison of two artifacts, not a live read."""
    ev, data = (p.file(acl_path) if acl_path else p.blob(t.head, "ops/ACL_MANIFEST_public.tsv"))
    if data is None:
        p.add(s, "UNTESTED", f"{t.label}: no ACL manifest at its head, so the production baseline cannot be compared with it", [base_ev])
        return
    rows = parse_acl(data.decode("utf8", "replace"))
    allrows = [l.split("\t") for l in data.decode("utf8", "replace").splitlines()[1:] if l.count("\t") >= 5]
    bucket = "VERIFIED" if fresh else "UNTESTED"
    evs = [ev, base_ev]
    mf = {r["name"]: r for r in rows if r["kind"] == "function"}
    bf = {f["sig"]: f for f in base.get("functions", []) if isinstance(f, dict)}
    new = sorted(set(mf) - set(bf))
    gone = sorted(set(bf) - set(mf))
    diff = []
    for n in sorted(set(mf) & set(bf)):
        ex = bf[n].get("execute", {})
        for role in ("anon", "authenticated", "service_role"):
            if (mf[n][role] != "-") != bool(ex.get(role)):
                diff.append(f"{n}[{role}]")
    sec = [n for n in set(mf) & set(bf) if (mf[n]["security"] == "security_definer") != (bf[n].get("security") == "definer")]
    p.add(s, bucket, f"{t.label} manifest vs production baseline, FUNCTIONS: {len(set(mf) & set(bf))} in both; {len(new)} only in the head manifest (to be created: {', '.join(new[:12])}{' ...' if len(new) > 12 else ''}); {len(gone)} only in production ({', '.join(gone[:12]) or 'none'}); {len(diff)} execute-privilege differences ({', '.join(diff[:10]) or 'none'}); {len(sec)} security-type differences", evs, cap=1500)
    mt = {r[1]: r for r in allrows if r[0] == "table"}
    bt = {x["name"]: x for x in base.get("tables", []) if isinstance(x, dict)}
    tdiff = []
    for n in sorted(set(mt) & set(bt)):
        for idx, role in ((2, "anon"), (3, "authenticated"), (4, "service_role")):
            m = set() if mt[n][idx] == "-" else set(mt[n][idx].split(","))
            if m != set(bt[n].get(role) or []):
                tdiff.append(f"{n}[{role}]")
    p.add(s, bucket, f"{t.label} manifest vs production baseline, TABLES: {len(set(mt) & set(bt))} in both; {len(set(mt) - set(bt))} only in manifest ({', '.join(sorted(set(mt) - set(bt))[:12]) or 'none'}); {len(set(bt) - set(mt))} only in production ({', '.join(sorted(set(bt) - set(mt))[:12]) or 'none'}); {len(tdiff)} privilege differences, e.g. {', '.join(tdiff[:8]) or 'none'}", evs, cap=1500)
    if tdiff:
        p.add(s, "UNTESTED", f"{t.label}: the committed manifest's TABLE privileges differ from production for {len(tdiff)} table/role pairs, so the manifest is a scratch-replica catalog, not a statement about production's post-lockdown table ACLs; do not read section 3 table rows as production state", evs)


def sec12(p, args, ts=(), acl_override=None):
    s = "s12"
    env = p.env
    base_ev = None
    if args.prod_baseline and env.read_file(args.prod_baseline) is not None:
        ev, data = p.file(args.prod_baseline)
        rec_ts, j = None, None
        try:
            j = json.loads(data)
            for k in ("captured_at", "taken_at", "generated_at", "generated_utc", "timestamp"):
                if isinstance(j, dict) and j.get(k):
                    rec_ts = j[k]
                    break
        except ValueError:
            pass
        age = None
        if rec_ts:
            try:
                age = (env.now() - datetime.datetime.fromisoformat(str(rec_ts).replace("Z", "+00:00"))).total_seconds() / 3600
            except ValueError:
                age = None
        shape = f"{len(j)} top-level keys ({', '.join(list(j)[:8])})" if isinstance(j, dict) else f"{type(j).__name__} of {len(j)}" if j is not None else "not JSON"
        p.add(s, "VERIFIED", f"production baseline artifact {args.prod_baseline} sha256 {sha256(data)}: {shape}; recorded time {rec_ts or 'NONE'}", [ev])
        base_ev = (ev, age)
        fresh = age is not None and age <= args.max_prod_age_hours
        if not fresh:
            p.add(s, "UNTESTED", f"the baseline is not fresh ({'no readable timestamp' if age is None else f'{age:.1f} h old'}; limit {args.max_prod_age_hours} h): it cannot support a 'matches production now' claim", [ev])
        else:
            p.add(s, "VERIFIED", f"baseline recorded {rec_ts}, {age:.2f} h before this run (limit {args.max_prod_age_hours} h); read_only flag in file = {j.get('read_only') if isinstance(j, dict) else None}. The tool did NOT take this snapshot; it only hashed the file, so 'taken read-only' rests on whoever produced it", [ev])
        if isinstance(j, dict):
            c = j.get("counts") or {}
            p.add(s, "VERIFIED" if fresh else "UNTESTED", f"baseline counts: {', '.join(f'{k}={v}' for k, v in c.items())}; migrations_latest: {', '.join(j.get('migrations_latest') or [])}; function md5 vs ops/live_function_md5_20261113: {json.dumps(j.get('function_md5_vs_ops_live_function_md5_20261113'))}", [ev])
            dp = j.get("deploys") or {}
