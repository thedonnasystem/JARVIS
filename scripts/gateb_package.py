class Env:
    """All outside access (gh, git, files, clock) goes through here so tests can fake it."""

    def __init__(self, repo_dir=None, now=None, no_fetch=False):
        self.repo_dir = repo_dir or os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
        self.now = now or utcnow
        self.no_fetch = no_fetch

    def gh(self, path):
        """GET repos/<REPO>/<path> via the gh CLI (REST). Returns (raw_bytes, None) or (None, error)."""
        try:
            r = subprocess.run(["gh", "api", f"repos/{REPO}/{path}"], capture_output=True, timeout=120)
        except Exception as e:  # noqa: BLE001
            return None, f"{type(e).__name__}: {e}"
        if r.returncode != 0:
            return None, one_line(r.stderr.decode("utf8", "replace") or "gh api failed", 300)
        return r.stdout, None

    def git(self, *args):
        try:
            r = subprocess.run(["git", "-C", self.repo_dir, *args], capture_output=True, timeout=120)
        except Exception:  # noqa: BLE001
            return None
        return r.stdout if r.returncode == 0 else None

    def git_grep(self, sha, pattern):
        try:
            r = subprocess.run(["git", "-C", self.repo_dir, "grep", "-n", "-E", pattern, sha, "--", "*.py"], capture_output=True, timeout=120)
        except Exception:  # noqa: BLE001
            return None
        return r.stdout if r.returncode in (0, 1) else None

    def have_commit(self, sha):
        return self.git("cat-file", "-e", sha + "^{commit}") is not None

    def fetch_branch(self, branch):
        if self.no_fetch:
            return False
        return self.git("fetch", "-q", "origin", f"+refs/heads/{branch}:refs/remotes/origin/{branch}") is not None

    def read_file(self, path):
        try:
            with open(path, "rb") as f:
                return f.read()
        except OSError:
            return None


# ------------------------------------------------------------------------------------------------------------------- package
class Pkg:
    def __init__(self, env):
        self.env = env
        self.ev = {}  # id -> dict
        self._dedupe = {}
        self._blobs = {}
        self.cnt = {"E": 0, "A": 0}
        self.sec = {k: [] for k, _, _ in SECTIONS}

    # evidence
    def _new(self, prefix, kind, ref, data):
        h = sha256(data)
        key = (kind, ref, h)
        if key in self._dedupe:
            return self._dedupe[key]
        self.cnt[prefix] += 1
        i = f"{prefix}{self.cnt[prefix]}"
        self.ev[i] = {"id": i, "kind": kind, "ref": ref.replace(" | ", " / ").replace("\n", " "), "sha256": h, "read_at": iso(self.env.now()), "bytes": len(data)}
        self._dedupe[key] = i
        return i

    def file(self, path):
        data = self.env.read_file(path)
        return (self._new("E", "file", os.path.abspath(path), data), data) if data is not None else (None, None)

    def blob(self, sha, path):
        if (sha, path) not in self._blobs:
            self._blobs[(sha, path)] = self.env.git("show", f"{sha}:{path}")
        data = self._blobs[(sha, path)]
        return (self._new("E", "git", f"{sha}:{path}", data), data) if data is not None else (None, None)

    def grep(self, sha, pattern):
        data = self.env.git_grep(sha, pattern)
        return (self._new("E", "git", f"{sha}:git grep -n -E {pattern[:60]}...", data), data.decode("utf8", "replace").splitlines()) if data is not None else (None, None)

    def listing(self, sha, prefix=""):
        data = self.env.git("ls-tree", "-r", "--name-only", sha, *([prefix] if prefix else []))
        return (self._new("E", "git", f"{sha}:ls-tree {prefix or '.'}", data), data.decode("utf8", "replace").splitlines()) if data is not None else (None, None)

    def api(self, path):
        data, err = self.env.gh(path)
        if data is None:
            return None, None, err
        try:
            obj = json.loads(data)
        except ValueError as e:
            return None, None, f"bad JSON: {e}"
        return self._new("A", "api", f"GET repos/{REPO}/{path}", data), obj, None

    # lines
    def add(self, sec, bucket, text, ev=(), cap=700):
        assert bucket in BUCKETS, bucket
        ev = [e for e in dict.fromkeys(ev) if e]
        if bucket in EVIDENCE_REQUIRED and not ev:
            raise ValueError(f"{bucket} line without evidence: {text[:80]}")
        for e in ev:
            if e not in self.ev:
                raise ValueError(f"unknown evidence id {e}")
        self.sec[sec].append((bucket, one_line(text, cap), ev))

    def counts(self):
        c = {b: 0 for b in BUCKETS}
        for k in self.sec:
            for b, _, _ in self.sec[k]:
                c[b] += 1
        return c


def bind(declared, head):
    """'head' if the declared commit is the current head, 'older' if it names another commit, 'unbound' if nothing is declared."""
    if not declared:
        return "unbound"
    d = declared.lower()
    return "head" if len(d) >= 7 and head.lower().startswith(d) else "older"


def bind_note(b, declared, head):
    if b == "older":
        return f" [covers {declared[:7]}, NOT the current head {head[:7]}]"
    return "" if b == "head" else " [log not bound to a commit]"


def scratch(p, sec, b, text, ev, declared, head):
    """TESTED IN SCRATCH only when the artifact is bound to the current head; otherwise UNTESTED for this head."""
    if b == "head":
        p.add(sec, "TESTED IN SCRATCH", text, ev)
    else:
        p.add(sec, "UNTESTED", text + bind_note(b, declared, head) + " (not evidence for the current head)", ev)


