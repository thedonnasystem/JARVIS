def render(p, ts, args):
    for k, _, _ in SECTIONS:
        if not p.sec[k]:
            p.sec[k].append(("UNTESTED", "nothing was produced for this section", []))
    c = p.counts()
    L = ["# Gate B release package (generated draft)", ""]
    L += [f"Generated {iso(p.env.now())} by scripts/gateb_package.py. Targets: " + ", ".join(f"{t.label}@{(t.head or 'unknown')[:7]}" for t in ts) + ".", ""]
    L += ["## Standing disclaimer", ""] + [f"- {d}" for d in DISCLAIMER] + [""]
    L += ["## Bucket summary", ""] + [f"- {b}: {c[b]}" for b in BUCKETS] + [f"- TOTAL: {sum(c.values())}", ""]
    L += ["Buckets: VERIFIED = observed by the tool from CI / gh api / a file it hashed. TESTED IN SCRATCH = a scratch-run result in a hashed log bound to the current head. UNTESTED = everything else (no artifact, unbound or older artifact, unknown status, failure). REQUIRES OWNER DECISION = only the owner can decide.", ""]
    for i, (k, title, _) in enumerate(SECTIONS, 1):
        L += [f"## {i}. {title}", ""]
        for b, txt, ev in p.sec[k]:
            check = "[ ] " if k == "s14" and txt.startswith("[ ] ") else ""
            body = txt[4:] if check else txt
            L.append(f"- {check}[{b}] {body}" + (f" (evidence: {', '.join(ev)})" if ev else (" (evidence: none)" if b not in EVIDENCE_REQUIRED else "")))
        L.append("")
    L += ["## Evidence register", "", "Every artifact and API response the lines above rely on. `sha256` is of the exact bytes read at `read_at`.", ""]
    for e in p.ev.values():
        L.append(f"- {e['id']} | {e['kind']} | {e['ref']} | sha256={e['sha256']} | read_at={e['read_at']} | bytes={e['bytes']}")
    me = os.path.abspath(__file__)
    data = p.env.read_file(me) or b""
    L += ["", f"Tool: {me} sha256 {sha256(data)}", ""]
    return "\n".join(L)


# ------------------------------------------------------------------------------------------------------------------------- check
def check_package(text, recheck_files=True):
    errs = []
    lines = text.splitlines()
    reg = {}
    in_reg = False
    for l in lines:
        if l.startswith("## "):
            in_reg = l.strip() == "## Evidence register"
        elif in_reg and l.startswith("- "):
            m = REG_RE.match(l)
            if not m:
                errs.append(f"malformed evidence register line: {l[:100]}")
            else:
                try:
                    datetime.datetime.fromisoformat(m.group(5).replace("Z", "+00:00"))
                except ValueError:
                    errs.append(f"{m.group(1)}: unreadable read_at")
                reg[m.group(1)] = {"kind": m.group(2), "ref": m.group(3), "sha": m.group(4)}
    # sections
    heads = [(i, l) for i, l in enumerate(lines) if l.startswith("## ")]
    names = [l[3:].strip() for _, l in heads]
    for n, (k, title, sub) in enumerate(SECTIONS, 1):
        if not any(re.match(rf"^{n}\. ", x) and sub.lower() in x.lower() for x in names):
            errs.append(f"required section {n} ({title}) is missing")
    for need in ("Standing disclaimer", "Bucket summary", "Evidence register"):
        if need not in names:
            errs.append(f"required section '{need}' is missing")
    dis = ""
    counts = {b: 0 for b in BUCKETS}
    for idx, (i, l) in enumerate(heads):
        name = l[3:].strip()
        end = heads[idx + 1][0] if idx + 1 < len(heads) else len(lines)
        body = [x for x in lines[i + 1:end] if x.strip()]
        if name == "Standing disclaimer":
            dis = " ".join(body)
        m = re.match(r"^(\d+)\. ", name)
        if not m:
            continue
        if not body:
            errs.append(f"section '{name}' is empty")
        for x in body:
            cm = CLAIM_RE.match(x)
            if not cm:
                errs.append(f"section {m.group(1)}: line is not '- [BUCKET] text': {x[:90]}")
                continue
            if BUCKET_TAG_RE.match(cm.group(2)):
                errs.append(f"section {m.group(1)}: not exactly one bucket tag: {x[:90]}")
            b, ev = cm.group(1), cm.group(3)
            counts[b] += 1
            ids = [e.strip() for e in ev.split(",")] if ev and ev.strip() != "none" else []
            if b in EVIDENCE_REQUIRED and not ids:
                errs.append(f"section {m.group(1)}: {b} line without an evidence reference: {x[:90]}")
            for e in ids:
                if e not in reg:
                    errs.append(f"section {m.group(1)}: evidence {e} is not in the register: {x[:70]}")
    for ph in REQUIRED_DISCLAIMER_PHRASES:
        if ph.lower() not in dis.lower():
            errs.append(f"standing disclaimer lacks '{ph}'")
    summ = {}
    for l in lines:
        m = re.match(r"^- (VERIFIED|TESTED IN SCRATCH|UNTESTED|REQUIRES OWNER DECISION): (\d+)$", l)
        if m:
            summ[m.group(1)] = int(m.group(2))
    for b in BUCKETS:
        if summ.get(b) != counts[b]:
            errs.append(f"bucket summary for {b} says {summ.get(b)} but the document has {counts[b]}")
    if recheck_files:
        for i, e in reg.items():
            if e["kind"] == "file" and os.path.exists(e["ref"]):
                with open(e["ref"], "rb") as f:
                    if sha256(f.read()) != e["sha"]:
                        errs.append(f"{i}: {e['ref']} has changed since it was hashed (package is stale)")
    return errs


