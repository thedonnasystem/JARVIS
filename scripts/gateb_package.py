def split_path_sha(arg):
    """'KEY=PATH[@SHA]' -> (key, path, sha|None)."""
    if "=" not in arg:
        raise SystemExit(f"expected KEY=PATH[@SHA], got {arg!r}")
    key, rest = arg.split("=", 1)
    m = re.match(r"^(.*)@([0-9a-fA-F]{7,40})$", rest)
    return (key, m.group(1), m.group(2)) if m else (key, rest, None)


def sniff_sha(text):
    for line in text.splitlines()[:6]:
        m = re.search(r"head=([0-9a-f]{40})", line) or re.search(r"@\s*([0-9a-f]{40})\b", line) or re.search(r"@\s*([0-9a-f]{7,12})\b", line)
        if m:
            return m.group(1)
    return None


def parse_gate_log(text):
    steps = {}
    for m in re.finditer(r"^(unit|scripts-tests|lint|bundle|appcheck|webjs|replica|manifest|backup)\s+(PASS|FAIL|SKIPPED)\b\s*(.*)$", text, re.M):
        steps[m.group(1)] = (m.group(2), m.group(3).strip())
    ran = [(int(m.group(1)), m.group(2)) for m in re.finditer(r"Ran (\d+) tests? in [^\n]*\n(?:[^\n]*\n){0,2}?\s*(OK|FAILED)", text)]
    drill = [(int(a), int(b)) for a, b in re.findall(r"^\s*(\d+)/(\d+) checks passed", text, re.M)]
    return {
        "steps": steps,
        "has_summary": "GATE SUMMARY" in text,
        "passed_line": (re.search(r"^GATE (PASSED[^\n]*|FAILED[^\n]*)", text, re.M) or [None, None])[1],
        "ran": ran,
        "drill": drill,
        "rollback_ok": bool(re.search(r"rollback drill OK", text)),
        "acl_match": bool(re.search(r"acl manifest matches", text)),
        "replica_ok": bool(re.search(r"^REPLICA OK", text, re.M)),
        "seen": re.findall(r"^>>> ([\w-]+):", text, re.M),
    }


def parse_unit_log(text):
    """unittest -v output -> {'module.Class.test': 'ok'|'FAIL'|...} keyed also by bare test name."""
    res = {}
    for m in re.finditer(r"^(test\w*) \(([\w.]+)\)[^\n]*?(?:\n[^\n]*?)? \.\.\. (ok|FAIL|ERROR|skipped[^\n]*|expected failure|unexpected success)$", text, re.M):
        res.setdefault(m.group(1), []).append((m.group(2), m.group(3)))
    return res


def parse_findings(text):
    """Heading-level findings: a heading with a severity word and an id (F1, B2b, N3, E2a ...). Returns (reviewed_sha, verdict_line, verdict_counts, findings)."""
    lines = text.splitlines()
    sha = sniff_sha(text)
    verdict = next((l for l in lines if re.match(r"^#{1,4}\s+Verdict\b", l)), None)
    vc = None
    if verdict:
        vc = {k: 0 for k in ("BLOCKER", "SHOULD-FIX", "NOTE")}
        for n, k in re.findall(r"\b(\d+|no)\s+(BLOCKER|SHOULD-FIX|NOTE)\b", verdict):
            vc[k] = 0 if n == "no" else int(n)
    heads = [(i, m) for i, l in enumerate(lines) for m in [re.match(r"^(#{2,5})\s+(.*)$", l)] if m]
    out = []
    for j, (i, m) in enumerate(heads):
        rest = m.group(2)
        if re.match(r"Verdict\b", rest):
            continue
        sm = re.search(r"\b(BLOCKER|SHOULD-FIX|MUST-FIX|NOTE)\b", rest)
        if not sm:
            continue
        idm = re.search(r"\b([A-Z]{1,3}\d+[a-z]?)\b", rest.replace(sm.group(1), " "))
        if not idm:
            continue
        end = heads[j + 1][0] if j + 1 < len(heads) else len(lines)
        body = "\n".join(lines[i + 1:end])
        title = rest.split(":", 1)[1].strip() if ":" in rest else rest
        status, status_note = "status unknown", ""
        for sl in body.splitlines():
            ms = re.match(r"^\s*[-*]?\s*\**(?:status|resolution)\**\s*:\s*(.+)$", sl, re.I)
            if ms:
                v = ms.group(1).strip()
                low = v.lower()
                status = "owner-decision" if "owner" in low else "fixed" if re.search(r"\b(fixed|resolved|closed)\b", low) and not re.search(r"not (fixed|resolved)", low) else "open" if re.search(r"\b(open|unresolved|not fixed|wontfix)\b", low) else "status unknown"
                status_note = v
                break
        owner_flag = bool(re.search(r"owner decision|policy call for the owner|needs counsel|counsel call|owner must", title + " " + body, re.I))
        out.append({"id": idm.group(1), "severity": sm.group(1), "title": title, "status": status, "status_note": status_note, "owner_flag": owner_flag})
    return sha, (verdict or "").lstrip("# ").strip(), vc, out


def parse_resolutions(text):
    """Lines '<KEY>:<ID> | fixed|open|owner-decision | note' (KEY = findings label)."""
    res = {}
    for l in text.splitlines():
        m = re.match(r"^\s*[-*]?\s*`?([\w.-]+:[A-Za-z]{1,3}\d+[a-z]?)`?\s*\|\s*(fixed|open|owner-decision)\s*\|\s*(.*)$", l)
        if m:
            res[m.group(1)] = (m.group(2), m.group(3).strip())
    return res


def parse_acl(text):
    rows = []
    for l in text.splitlines()[1:]:
        c = l.split("\t")
        if len(c) >= 6:
            rows.append({"kind": c[0], "name": c[1], "anon": c[2], "authenticated": c[3], "service_role": c[4], "security": c[5]})
    return rows


def parse_owner_md(text):
    """Owner decisions from an OWNER_DECISIONS.md: table rows under a 'Decision' column, plus paragraph / numbered lines of sections that have no decision table."""
    items, section, hdr, sect_items, has_table = [], "", None, [], False

    def flush():
        if not has_table:
            items.extend(sect_items)

    for line in text.splitlines():
        hm = re.match(r"^(#{1,5})\s+(.*)$", line)
        if hm:
            flush()
            section, hdr, sect_items, has_table = hm.group(2).strip(), None, [], False
            continue
        if not section:
            continue
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if all(re.fullmatch(r":?-+:?", c) for c in cells if c):
                continue
            if hdr is None:
                hdr = [c.lower() for c in cells]
                continue
            if "decision" not in hdr:
                continue
            has_table = True
            row = dict(zip(hdr, cells))
            dcol = next((k for k in hdr if k.startswith("default")), None)
            bcol = next((k for k in hdr if k.startswith("blocks")), None)
            txt = f"{cells[0]} {row.get('decision', '')}"
            if dcol:
                txt += f" | default: {row.get(dcol, '')}"
            if bcol:
                txt += f" | blocks release: {row.get(bcol, '')}"
            items.append({"section": section, "text": one_line(txt, 420)})
        elif line.strip() and len(line.strip()) > 20 and not line.startswith("Legend:"):
            sect_items.append({"section": section, "text": one_line(line.strip(), 420)})
    flush()
    return items


def grep_owner_lines(text, cap=25):
    out = []
    for l in text.splitlines():
        if re.search(r"owner decision|requires owner|owner must decide", l, re.I) and len(l.strip()) > 15:
            out.append(one_line(l.strip().lstrip("-*| ").strip(), 300))
        if len(out) >= cap:
            break
    return out


def migration_entries(text):
    return [l.strip() for l in text.splitlines() if l.strip() and not l.lstrip().startswith("#")]


