def workflow_jobs(text):
    jobs, inj = [], False
    cur = None
    for l in text.splitlines():
        if re.match(r"^jobs:\s*$", l):
            inj = True
            continue
        if inj and re.match(r"^\S", l):
            inj = False
        if inj:
            m = re.match(r"^  ([\w-]+):\s*$", l)
            if m:
                cur = [m.group(1), m.group(1)]
                jobs.append(cur)
                continue
            m = re.match(r"^    name:\s*(.+?)\s*$", l)
            if m and cur:
                cur[1] = m.group(1).strip("'\"")
    return [j[1] for j in jobs]


