def build(args, env):
    p = Pkg(env)
    prs = [str(x) for x in (args.pr or [])]
    branches = list(args.branch or [])
    if args.manifest:
        m = json.loads(open(args.manifest).read())
        prs += [str(x) for x in m.get("prs", [])]
        branches += m.get("branches", [])
    if not prs and not branches:
        prs = [str(x) for x in DEFAULT_PRS]
    ts = gather_targets(p, list(dict.fromkeys(prs)), list(dict.fromkeys(branches)))
    spec = {"gate": args.gate_log or [], "unit": args.unit_log or [], "drill": args.drill_results or [], "findings": list(args.findings or []), "rollback": args.rollback_result or [], "differential": args.differential_log or []}
    if not args.no_defaults:
        for key, pat in DEFAULT_FINDINGS.items():
            if any(t.key == key for t in ts):
                spec["findings"] += [f"{key}={f}" for f in sorted(glob.glob(pat))]
    collect(p, ts, spec)
    resolutions = {}
    if args.resolutions:
        rd = p.file(args.resolutions)
        if rd[1] is not None:
            resolutions = parse_resolutions(rd[1].decode("utf8", "replace"))
    base = base_facts(p)
    base_files = set()
    if base:
        _, bf = p.listing(base["sha"], "ops")
        base_files = set(bf or [])
    acl = {}
    for a in args.acl_manifest or []:
        k, path, _ = split_path_sha(a)
        acl[find_target(ts, k).key] = path
    gates = gate_map(ts)
    sec1(p, ts, base)
    sec2(p, ts, base)
    sec3(p, ts, acl, gates)
    sec4(p, ts, resolutions)
    sec5(p, ts)
    sec6(p, ts, PROOF_TESTS)
    sec7(p, ts)
    sec8(p, ts)
    sec9(p, ts)
    sec10(p, ts)
    sec11(p, ts, base_files)
    sec12(p, args, ts, acl)
    n = sec14_and_13(p, ts, args.doc or DEFAULT_DOCS)
    # the head must not have moved while the tool was reading
    for t in ts:
        if t.kind == "pr" and t.head:
            ev, o, err = p.api(f"pulls/{t.key}")
            if o is None:
                p.add("s1", "UNTESTED", f"{t.label}: head re-check at end of run failed ({err})", [])
            elif o["head"]["sha"] != t.head:
                p.add("s1", "UNTESTED", f"{t.label}: HEAD MOVED during the run ({t.head[:7]} -> {o['head']['sha'][:7]}); results above are for the older head. Re-run.", [ev])
            else:
                p.add("s1", "VERIFIED", f"{t.label}: head re-read at end of run is unchanged ({t.head[:7]})", [ev])
    sec13(p, ts, n)
    return p, ts


def main(argv=None, env=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="verify an existing package instead of generating one")
    ap.add_argument("--package", default=DEFAULT_OUT)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--pr", action="append", type=int)
    ap.add_argument("--branch", action="append")
    ap.add_argument("--manifest", help="JSON {\"prs\": [..], \"branches\": [..]}")
    ap.add_argument("--gate-log", action="append", metavar="KEY=PATH[@SHA]", help="scripts/gate.sh output")
    ap.add_argument("--unit-log", action="append", metavar="KEY=PATH[@SHA]", help="python3 -m unittest discover -v output")
    ap.add_argument("--drill-results", action="append", metavar="KEY=PATH[@SHA]")
    ap.add_argument("--findings", action="append", metavar="KEY=PATH")
    ap.add_argument("--rollback-result", action="append", metavar="KEY=PATH[@SHA]")
    ap.add_argument("--differential-log", action="append", metavar="KEY=PATH[@SHA]")
    ap.add_argument("--acl-manifest", action="append", metavar="KEY=PATH")
    ap.add_argument("--resolutions")
    ap.add_argument("--doc", action="append", help="extra docs (path in repo) to grep for owner decisions")
    ap.add_argument("--prod-baseline", default=DEFAULT_PROD_BASELINE)
    ap.add_argument("--prod-compare")
    ap.add_argument("--max-prod-age-hours", type=float, default=MAX_PROD_AGE_H)
    ap.add_argument("--no-defaults", action="store_true", help="do not glob /home/claude/*_FINDINGS.md")
    ap.add_argument("--no-fetch", action="store_true")
    ap.add_argument("--repo-dir")
    args = ap.parse_args(argv)
    if args.check:
        with open(args.package, encoding="utf8") as f:
            errs = check_package(f.read())
        for e in errs:
            print("CHECK FAIL:", e)
        print(f"gateb_package --check: {len(errs)} problem(s)")
        return 1 if errs else 0
    env = env or Env(args.repo_dir, no_fetch=args.no_fetch)
    p, ts = build(args, env)
    text = render(p, ts, args)
    with open(args.out, "w", encoding="utf8") as f:
        f.write(text)
    errs = check_package(text)
    c = p.counts()
    print(f"wrote {args.out}: " + ", ".join(f"{b}={c[b]}" for b in BUCKETS) + f"; evidence entries={len(p.ev)}")
    for e in errs:
        print("SELF-CHECK FAIL:", e)
    return 2 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
