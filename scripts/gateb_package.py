def collect(p, ts, spec):
    """spec: kind -> list of KEY=PATH[@SHA]. Returns per-kind dict key -> list of artifacts; unreadable files are reported."""
    out = {}
    for kind, items in spec.items():
        for arg in items:
            key, path, sha = split_path_sha(arg)
            t = find_target(ts, key)
            a = load_art(p, t, kind, path, sha)
            if a is None:
                t.arts.setdefault("missing", []).append((kind, path))
            else:
                t.arts[kind].append(a)
    return out


