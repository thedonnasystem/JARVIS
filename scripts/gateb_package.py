class Target:
    def __init__(self, label, kind, key):
        self.label, self.kind, self.key = label, kind, key  # kind pr|branch
        self.branch = self.head = self.url = self.base_ref = self.title = None
        self.state = self.draft = None
        self.ev_head = None
        self.arts = {k: [] for k in ("gate", "unit", "drill", "findings", "rollback", "differential")}
        self.err = None


def gather_targets(p, prs, branches):
    ts = []
    for n in prs:
        t = Target(f"PR #{n}", "pr", str(n))
        ev, o, err = p.api(f"pulls/{n}")
        if o is None:
            t.err = f"GET pulls/{n} failed: {err}"
        else:
            t.ev_head, t.branch, t.head = ev, o["head"]["ref"], o["head"]["sha"]
            t.url, t.base_ref, t.title, t.state, t.draft = o.get("html_url"), o["base"]["ref"], o.get("title"), ("merged" if o.get("merged") else o.get("state")), o.get("draft")
        ts.append(t)
    for b in branches:
        t = Target(f"branch {b}", "branch", b)
        ev, o, err = p.api(f"git/ref/heads/{b}")
        if o is None:
            t.err = f"GET git/ref/heads/{b} failed: {err}"
        else:
            t.ev_head, t.branch, t.head = ev, b, o["object"]["sha"]
            t.url = f"https://github.com/{REPO}/tree/{b}"
        ts.append(t)
    for t in ts:
        if t.head and not p.env.have_commit(t.head):
            p.env.fetch_branch(t.branch)
    return ts


def find_target(ts, key):
    for t in ts:
        if t.key == key or t.branch == key or t.label == key:
            return t
    raise SystemExit(f"--* KEY {key!r} matches no PR/branch in the manifest ({[t.key for t in ts]})")


def sec1(p, ts, base_ev):
    s = "s1"
    for t in ts:
        if t.err:
            p.add(s, "UNTESTED", f"{t.label}: head SHA unknown, {t.err}", [])
            continue
        extra = f" state={t.state} draft={t.draft} base={t.base_ref} title={t.title!r}" if t.kind == "pr" else ""
        p.add(s, "VERIFIED", f"{t.label} `{t.branch}` head `{t.head}` {t.url}{extra}", [t.ev_head])
    if base_ev:
        p.add(s, "VERIFIED", base_ev["text"], base_ev["ev"])
    else:
        p.add(s, "UNTESTED", f"latest merged base: could not read {BASE_BRANCH} from the API", [])
    for t in ts:
        if t.err or not t.head:
            continue
        ev, o, err = p.api(f"compare/{BASE_BRANCH}...{t.head}")
        if o is None:
            p.add(s, "UNTESTED", f"{t.label}: ahead/behind vs {BASE_BRANCH} unknown ({err})", [])
        else:
            p.add(s, "VERIFIED", f"{t.label}: {o.get('ahead_by')} commit(s) ahead and {o.get('behind_by')} behind current {BASE_BRANCH} (compare status {o.get('status')})", [ev])


def base_facts(p):
    ev1, b, err = p.api(f"branches/{BASE_BRANCH}")
    if b is None:
        return None
    sha = b["commit"]["sha"]
    ev2, prs, err2 = p.api(f"pulls?state=closed&base={BASE_BRANCH}&sort=updated&direction=desc&per_page=30")
    merged = [x for x in (prs or []) if x.get("merged_at")]
    merged.sort(key=lambda x: x["merged_at"], reverse=True)
    txt = f"base `{BASE_BRANCH}` head `{sha}`"
    evs = [ev1]
    if merged:
        m = merged[0]
        txt += f"; latest merged PR #{m['number']} `{m['head']['ref']}` merged_at {m['merged_at']} merge commit `{m.get('merge_commit_sha')}`"
        evs.append(ev2)
    else:
        txt += "; no merged PR found in the last 30 closed PRs"
        if ev2:
            evs.append(ev2)
    return {"text": txt, "ev": evs, "sha": sha}


