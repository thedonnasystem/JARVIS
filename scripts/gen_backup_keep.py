#!/usr/bin/env python3
"""Writes hq_backup_keep.py: the (table, column) pairs the export spec classifies KEEP (identifiers, codes, statuses, unique keys), parsed from backup_redaction_spec() in
migrations/20261120_backup_redact_leak_paths_v1.sql. hq_backup.py's two-read fallback (no database redactor) blanks EVERY other string, so a column the spec marks strict or light, and
a column nobody classified yet, can never be exported raw. test_hq_backup.py fails when the generated file is stale.   python3 scripts/gen_backup_keep.py [--check]"""
import os, re, sys
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SQL = os.path.join(ROOT, "migrations", "20261120_backup_redact_leak_paths_v1.sql")
OUT = os.path.join(ROOT, "hq_backup_keep.py")
ROW = re.compile(r"^\s*\('([a-z0-9_]+)', '([a-z0-9_]+)', '(text|json|array)', '(strict|light|keep|blank|slug)', (?:null|\d+), '", re.M)


def spec():
    s = open(SQL).read()
    a = s.index("function public.backup_redaction_spec()")
    b = s.index("$$;", s.index("select * from (values", a))
    return [m.groups()[:4] for m in ROW.finditer(s[a:b])]


def render():
    rows = spec()
    keep = sorted((t, c) for t, c, _k, m in rows if m == "keep")
    out = ['"""GENERATED by scripts/gen_backup_keep.py from backup_redaction_spec(): do not edit. KEEP columns of the export spec; the two-read fallback blanks every other string."""',
           f"SPEC_COLUMNS = {len(rows)}", "KEEP = {"]
    cur = None
    for t, c in keep:
        out.append(f"    ({t!r}, {c!r}),")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if open(OUT).read() == text else 1)
    open(OUT, "w").write(text); print("wrote", OUT)
